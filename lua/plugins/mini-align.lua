-- Выравнивание текста по символу (mini.align): <leader>= , например по «=» или «:».
-- Использование: выделите строки (V) → <leader>= → введите символ (например «=»).
-- В normal-режиме: <leader>= и затем движение (например <leader>=ip — абзац).
-- Стандартный ga не трогаем: он нужен для Go-клавиш (ga — файл↔тест).
return {
  {
    "nvim-mini/mini.align",
    keys = {
      { "<leader>=", mode = { "n", "x" }, desc = "↔ Выровнять по символу (mini.align)" },
    },
    opts = {
      mappings = {
        start = "<leader>=",
        start_with_preview = "", -- отключено: предпросмотр не нужен
      },
    },
  },
}
